#!/usr/bin/env python3
"""Generate src/ap/ap_catalog.h from archipelago/animaniacs/catalog.json.

    python scripts/gen_ap_catalog.py           # write the header
    python scripts/gen_ap_catalog.py --check   # fail if the header is stale
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CATALOG = ROOT / "archipelago" / "animaniacs" / "catalog.json"
HEADER = ROOT / "src" / "ap" / "ap_catalog.h"


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(cat: dict) -> str:
    kinds = cat["kinds"]
    locs = cat["locations"]
    max_ms = max(sum(1 for l in locs if l["kind"] == "milestone" and l["level"] == lv["index"])
                 for lv in cat["levels"])
    out = [
        "/* Generated by scripts/gen_ap_catalog.py from",
        " * archipelago/animaniacs/catalog.json. Do not edit. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define ANI_AP_GAME {c_str(cat['game'])}",
        f"#define ANI_AP_CATALOG_VERSION {cat['catalog_version']}",
        f"#define ANI_AP_BASE_ID {cat['base_id']}LL",
        f"#define ANI_AP_EDGAR_ITEM {cat['edgar_item']['id']}LL",
        f"#define ANI_AP_FILLER_ITEM {cat['filler_item']['id']}LL",
        f"#define ANI_AP_LEVELS {len(cat['levels'])}",
        f"#define ANI_AP_ABILITIES {len(cat['abilities'])}",
        f"#define ANI_AP_MAX_MILESTONES {max_ms}",
        f"#define ANI_AP_LOCATIONS {len(locs)}",
        "/* Location ID = ANI_AP_BASE_ID + kind * 0x10000 + level * 0x1000 + index. */",
    ]
    for k, v in kinds.items():
        out.append(f"#define ANI_AP_KIND_{k.upper()} {v}")
    out += [
        "#define ANI_AP_KIND_OF(id) ((int)(((id) - ANI_AP_BASE_ID) >> 16))",
        "",
        "typedef struct { const char *name, *collectible; int collectibles;",
        "                 int milestones; int milestone_step;",
        "                 int64_t milestone[ANI_AP_MAX_MILESTONES]; } AniApLevel;",
        "typedef struct { uint16_t bit; const char *key, *name; int64_t item, location; } AniApAbility;",
        "/* A pickup object (by its level and objectname) and the check it is. */",
        "typedef struct { int8_t level; const char *object; int64_t location; } AniApObject;",
        "/* Objects named by a prefix: the per-room copies of an Edgar. */",
        "typedef struct { int8_t level; const char *prefix; int64_t location; } AniApPrefix;",
        "typedef struct { int64_t id; const char *name; } AniApName;",
        "",
        "static const AniApLevel ani_ap_levels[ANI_AP_LEVELS] = {",
    ]
    for lv in cat["levels"]:
        ms = [l for l in locs if l["kind"] == "milestone" and l["level"] == lv["index"]]
        step = ms[0]["count"] if ms else 0
        ids = ", ".join(f"{l['id']}LL" for l in ms) or "0"
        out.append(f"    {{{c_str(lv['name'])}, {c_str(lv['collectible'])}, {lv['collectibles']}, "
                   f"{len(ms)}, {step}, {{{ids}}}}},")
    out += ["};", "", "static const AniApAbility ani_ap_abilities[ANI_AP_ABILITIES] = {"]
    for a in cat["abilities"]:
        out.append(f"    {{0x{a['bit']:03X}, {c_str(a['key'])}, {c_str(a['name'])}, "
                   f"{a['item']}LL, {a['location']['id']}LL}},")
    objs = [(l["level"], o, l["id"]) for l in locs for o in l.get("objects", [])]
    out += ["};", "", f"#define ANI_AP_OBJECTS {len(objs)}",
            "static const AniApObject ani_ap_objects[ANI_AP_OBJECTS] = {"]
    for lvl, o, i in objs:
        out.append(f"    {{{lvl}, {c_str(o)}, {i}LL}},")
    prefixes = [l for l in locs if "prefix" in l]
    out += ["};", "", f"#define ANI_AP_PREFIXES {len(prefixes)}",
            "static const AniApPrefix ani_ap_prefixes[ANI_AP_PREFIXES] = {"]
    for l in prefixes:
        out.append(f"    {{{l['level']}, {c_str(l['prefix'])}, {l['id']}LL}},")
    names = sorted([(l["id"], l["name"]) for l in locs] +
                   [(a["location"]["id"], a["location"]["name"]) for a in cat["abilities"]])
    out += ["};", "", f"#define ANI_AP_NAMES {len(names)}",
            "/* Sorted by ID. */",
            "static const AniApName ani_ap_location_names[ANI_AP_NAMES] = {"]
    for i, n in names:
        out.append(f"    {{{i}LL, {c_str(n)}}},")
    out += ["};", ""]
    return "\n".join(out)


def main() -> int:
    text = render(json.loads(CATALOG.read_text()))
    if "--check" in sys.argv:
        if not HEADER.exists() or HEADER.read_text() != text:
            print(f"{HEADER} is stale: run scripts/gen_ap_catalog.py", file=sys.stderr)
            return 1
        return 0
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text(text, newline="\n")
    print(HEADER)
    return 0


if __name__ == "__main__":
    sys.exit(main())
